private enum G13IconImportError: LocalizedError {
    case invalidImage
    case tooLarge
    case unavailableFolder

    var errorDescription: String? {
        switch self {
        case .invalidImage: return "Choose a valid PNG or JPEG image no larger than 1024 × 1024 pixels."
        case .tooLarge: return "Choose an image file smaller than 2 MB."
        case .unavailableFolder: return "The app could not access its local icon folder."
        }
    }
}

