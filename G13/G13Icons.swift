    static let composedIcons: [(title: String, reference: String)] = [
        ("Save As", "studio:save-as"),
        ("Duplicate in Front", "studio:duplicate-front"),
        ("Paste", "studio:paste"), ("Left Click", "studio:left-click"),
        ("Right Click", "studio:right-click"),
        ("Shift + S", "studio:shift-s"),
        ("Numpad −", "studio:numpad-minus"),
        ("Numpad +", "studio:numpad-plus")
    ]

    static func matchingComposedIcons(_ query: String) -> [(title: String, reference: String)] {
        let search = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !search.isEmpty else { return composedIcons }
        return composedIcons.filter { $0.title.localizedCaseInsensitiveContains(search) }
    }

    static func matchingSymbols(_ query: String) -> [(title: String, name: String)] {
        let search = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !search.isEmpty else { return symbols }
        return symbols.filter {
            $0.title.localizedCaseInsensitiveContains(search) ||
            $0.name.localizedCaseInsensitiveContains(search)
        }
    }

    private static let cache = NSCache<NSString, NSImage>()

    private static var iconFolder: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)
            .first?.appendingPathComponent("com.openg13.G13/Icons", isDirectory: true)
    }

    // Only names generated by this app may be used as file references.
    static func image(for reference: String) -> NSImage? {
        guard reference.hasPrefix("custom:") else { return nil }
        let filename = String(reference.dropFirst("custom:".count))
        guard filename.hasSuffix(".png"),
              UUID(uuidString: String(filename.dropLast(4))) != nil,
              let folder = iconFolder else { return nil }
        if let cached = cache.object(forKey: reference as NSString) { return cached }
        let url = folder.appendingPathComponent(filename)
        guard let size = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey]),
              size.isRegularFile == true, let fileSize = size.fileSize, fileSize <= 4_000_000,
              let data = try? Data(contentsOf: url),
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) == 1,
              let raster = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let normalized = try? normalizedPNGData(from: raster),
              let image = NSImage(data: normalized) else { return nil }
        cache.setObject(image, forKey: reference as NSString)
        return image
    }

    static func backupData(for reference: String) throws -> Data {
        guard let filename = validatedFilename(for: reference), let folder = iconFolder else {
            throw G13IconImportError.invalidImage
        }
        let url = folder.appendingPathComponent(filename)
        let values = try url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey])
        guard values.isRegularFile == true, let size = values.fileSize, size <= 4_000_000 else {
            throw G13IconImportError.tooLarge
        }
        return try Data(contentsOf: url)
    }

    static func restoreBackupData(_ data: Data) throws -> String {
        guard data.count <= 4_000_000,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) == 1,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as NSDictionary?,
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              (1...1024).contains(width), (1...1024).contains(height),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
              let folder = iconFolder else { throw G13IconImportError.invalidImage }
        let output = try normalizedPNGData(from: image)
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let filename = UUID().uuidString + ".png"
        try output.write(to: folder.appendingPathComponent(filename), options: .atomic)
        return "custom:" + filename
    }

    private static func validatedFilename(for reference: String) -> String? {
        guard reference.hasPrefix("custom:") else { return nil }
        let filename = String(reference.dropFirst("custom:".count))
        guard filename.hasSuffix(".png"),
              UUID(uuidString: String(filename.dropLast(4))) != nil else { return nil }
        return filename
    }

    // Store a centered square PNG so every imported icon uses the same canvas.
    // Transparent margins are trimmed before fitting the artwork into it.
    static func normalizedPNGData(from image: CGImage) throws -> Data {
        guard (1...1024).contains(image.width), (1...1024).contains(image.height) else {
            throw G13IconImportError.invalidImage
        }
        let bitmapInfo = CGBitmapInfo.byteOrder32Big.rawValue |
            CGImageAlphaInfo.premultipliedLast.rawValue
        let colorSpace = CGColorSpaceCreateDeviceRGB()
        guard let source = CGContext(data: nil, width: image.width, height: image.height,
                                     bitsPerComponent: 8, bytesPerRow: 0,
                                     space: colorSpace, bitmapInfo: bitmapInfo),
              let sourceData = source.data else { throw G13IconImportError.invalidImage }
        source.clear(CGRect(x: 0, y: 0, width: image.width, height: image.height))
        source.draw(image, in: CGRect(x: 0, y: 0, width: image.width, height: image.height))
        let pixels = sourceData.assumingMemoryBound(to: UInt8.self)
        var minX = image.width, minY = image.height, maxX = -1, maxY = -1
        for y in 0..<image.height {
            for x in 0..<image.width where pixels[y * source.bytesPerRow + x * 4 + 3] > 8 {
                minX = min(minX, x)
                minY = min(minY, y)
                maxX = max(maxX, x)
                maxY = max(maxY, y)
            }
        }
        guard maxX >= minX, maxY >= minY,
              let raster = source.makeImage(),
              let cropped = raster.cropping(to: CGRect(x: minX, y: minY,
                                                       width: maxX - minX + 1,
                                                       height: maxY - minY + 1)),
              let canvas = CGContext(data: nil, width: importedIconSide, height: importedIconSide,
                                     bitsPerComponent: 8, bytesPerRow: 0,
                                     space: colorSpace, bitmapInfo: bitmapInfo) else {
            throw G13IconImportError.invalidImage
        }
        let maximumArtworkSide: CGFloat = 112
        let scale = min(maximumArtworkSide / CGFloat(cropped.width),
                        maximumArtworkSide / CGFloat(cropped.height))
        let width = CGFloat(cropped.width) * scale
        let height = CGFloat(cropped.height) * scale
        canvas.clear(CGRect(x: 0, y: 0, width: importedIconSide, height: importedIconSide))
        canvas.draw(cropped, in: CGRect(x: (CGFloat(importedIconSide) - width) / 2,
                                        y: (CGFloat(importedIconSide) - height) / 2,
                                        width: width, height: height))
        guard let normalized = canvas.makeImage() else { throw G13IconImportError.invalidImage }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output,
                                            UTType.png.identifier as CFString, 1, nil) else {
            throw G13IconImportError.invalidImage
        }
        CGImageDestinationAddImage(destination, normalized, nil)
        guard CGImageDestinationFinalize(destination), output.length <= 4_000_000 else {
            throw G13IconImportError.tooLarge
        }
        return output as Data
    }

    static func importFromPicker() throws -> String? {
        let panel = NSOpenPanel()
        panel.allowedContentTypes = [.png, .jpeg]
        panel.canChooseDirectories = false
        panel.canChooseFiles = true
        panel.allowsMultipleSelection = false
        panel.message = "Choose a command or key icon (PNG or JPEG, up to 1024 × 1024 pixels)"
        guard panel.runModal() == .OK, let url = panel.url else { return nil }
        let scoped = url.startAccessingSecurityScopedResource()
        defer { if scoped { url.stopAccessingSecurityScopedResource() } }
        let values = try url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey])
        guard values.isRegularFile == true else { throw G13IconImportError.invalidImage }
        guard let size = values.fileSize, size <= 2_000_000 else { throw G13IconImportError.tooLarge }
        let data = try Data(contentsOf: url)
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) == 1,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as NSDictionary?,
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              (1...1024).contains(width), (1...1024).contains(height),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else {
            throw G13IconImportError.invalidImage
        }
        let output = try normalizedPNGData(from: image)
        guard let folder = iconFolder else { throw G13IconImportError.unavailableFolder }
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let filename = UUID().uuidString + ".png"
        try output.write(to: folder.appendingPathComponent(filename), options: .atomic)
        return "custom:" + filename
    }
}

enum G13IconColor: String, CaseIterable {
    case automatic, black, white, teal, blue, green, orange, purple, red, original

    var title: String { rawValue.capitalized }
    var color: Color {
        switch self {
        case .automatic, .original: return .primary
        case .black: return .black
        case .white: return .white
        case .teal: return .teal
        case .blue: return .blue
        case .green: return .green
        case .orange: return .orange
        case .purple: return .purple
        case .red: return .red
        }
    }
}

struct G13IconColorPicker: View {
    @Binding var selection: String?
    var body: some View {
        Picker("Icon color", selection: Binding(
            get: { selection ?? "inherit" },
            set: { selection = $0 == "inherit" ? nil : $0 }
        )) {
            Text("Use shared color").tag("inherit")
            ForEach(G13IconColor.allCases, id: \.rawValue) { option in
                Text(option.title).tag(option.rawValue)
            }
        }
        .pickerStyle(.menu)
    }
}

struct G13IconView: View {
    let reference: String?
    var colorOverride: String? = nil
    @AppStorage("studioDefaultIconColor") private var sharedColor = "automatic"

    private var chosenColor: G13IconColor {
        G13IconColor(rawValue: colorOverride ?? sharedColor) ?? .automatic
    }

    var body: some View {
        GeometryReader { geometry in
            let side = min(geometry.size.width, geometry.size.height)
            ZStack {
                if reference == "studio:save-as" {
                    Image(systemName: "square.and.arrow.down")
                        .font(.system(size: side * 0.72, weight: .medium))
                        .offset(x: -side * 0.07, y: -side * 0.07)
                    Image(systemName: "plus.circle.fill")
                        .font(.system(size: side * 0.35))
                        .offset(x: side * 0.28, y: side * 0.28)
                } else if reference == "studio:duplicate-front" {
                    Image(systemName: "square.on.square")
                        .font(.system(size: side * 0.8, weight: .medium))
                        .scaleEffect(x: -1, y: 1)
                } else if reference == "studio:paste" {
                    Image(systemName: "doc.on.clipboard")
                        .font(.system(size: side * 0.8, weight: .medium))
                } else if reference == "studio:left-click" || reference == "studio:right-click" {
                    Image(systemName: "cursorarrow.click")
                        .font(.system(size: side * 0.8, weight: .medium))
                        .scaleEffect(x: reference == "studio:right-click" ? -1 : 1, y: 1)
                } else if reference == "studio:shift-s" {
                    HStack(spacing: side * 0.04) {
                        Image(systemName: "shift.fill").font(.system(size: side * 0.52))
                        Text("S").font(.system(size: side * 0.60, weight: .bold, design: .rounded))
                    }
                } else if reference == "studio:numpad-minus" || reference == "studio:numpad-plus" {
                    ZStack {
                        RoundedRectangle(cornerRadius: side * 0.13)
                            .strokeBorder(lineWidth: max(1, side * 0.07))
                            .frame(width: side * 0.72, height: side * 0.78)
                        Image(systemName: reference == "studio:numpad-plus" ? "plus" : "minus")
                            .font(.system(size: side * 0.43, weight: .bold))
                    }
                } else if let reference, reference.hasPrefix("sf:") {
                    Image(systemName: String(reference.dropFirst(3)))
                        .font(.system(size: side * 0.8, weight: .medium))
                } else if let reference, let image = G13IconStore.image(for: reference) {
                    if chosenColor == .original {
                        Image(nsImage: image).resizable().scaledToFit()
                            .frame(width: side * 0.88, height: side * 0.88)
                    } else {
                        Image(nsImage: image).renderingMode(.template).resizable().scaledToFit()
                            .frame(width: side * 0.88, height: side * 0.88)
                    }
                } else {
                    Image(systemName: "square.dashed")
                        .font(.system(size: side * 0.75))
                        .foregroundStyle(.secondary)
                }
            }
            .foregroundStyle(chosenColor.color)
            .frame(width: geometry.size.width, height: geometry.size.height)
        }
    }
}

struct G13IconPicker: View {
    let selectedReference: String?
    let inheritedReference: String?
    let allowInherit: Bool
    let onSelect: (String?) -> Void
    @State private var importError: String?
    @State private var showLibrary = false
    @State private var searchText = ""

    var body: some View {
        Button {
            searchText = ""
            showLibrary = true
        } label: {
            HStack(spacing: 8) {
                G13IconView(reference: selectedReference ?? inheritedReference)
                    .frame(width: 21, height: 21)
                Text("Choose icon")
            }
        }
        .popover(isPresented: $showLibrary) {
            VStack(alignment: .leading, spacing: 10) {
                Text("Choose icon").font(.headline)
                TextField("Search icons", text: $searchText)
                    .textFieldStyle(.roundedBorder)
                ScrollView {
                    LazyVGrid(columns: Array(repeating: GridItem(.flexible(), spacing: 8), count: 3),
                              spacing: 8) {
                        ForEach(G13IconStore.matchingComposedIcons(searchText), id: \.reference) { icon in
                            Button {
                                select(icon.reference)
                            } label: {
                                VStack(spacing: 5) {
                                    G13IconView(reference: icon.reference)
                                        .frame(width: 25, height: 25)
                                    Text(icon.title).font(.caption2).lineLimit(2)
                                }
                                .frame(maxWidth: .infinity, minHeight: 62)
                            }
                            .buttonStyle(.bordered)
                        }
                        ForEach(G13IconStore.matchingSymbols(searchText), id: \.name) { symbol in
                            Button {
                                select("sf:" + symbol.name)
                            } label: {
                                VStack(spacing: 5) {
                                    G13IconView(reference: "sf:" + symbol.name)
                                        .frame(width: 25, height: 25)
                                    Text(symbol.title).font(.caption2).lineLimit(2)
                                }
                                .frame(maxWidth: .infinity, minHeight: 62)
                            }
                            .buttonStyle(.bordered)
                        }
                    }
                }
                .frame(width: 390, height: 280)
                HStack {
                    if allowInherit {
                        Button("Use command icon") { select(nil) }
                        Button("No icon") { select("none") }
                    } else {
                        Button("No icon") { select(nil) }
                    }
                    Spacer()
                    Button("Import PNG or JPEG…") {
                        showLibrary = false
                        do {
                            if let reference = try G13IconStore.importFromPicker() {
                                onSelect(reference)
                            }
                        } catch {
                            importError = error.localizedDescription
                        }
                    }
                }
            }
            .padding(14)
        }
        .alert("Image could not be imported", isPresented: Binding(
            get: { importError != nil }, set: { if !$0 { importError = nil } }
        )) {
            Button("OK") { importError = nil }
        } message: {
            Text(importError ?? "")
        }
    }

    private func select(_ reference: String?) {
        onSelect(reference)
        showLibrary = false
    }
}
